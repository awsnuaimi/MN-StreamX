import com.yourapp.iptv.viewmodel.CaptionViewModel
import java.text.DateFormat
import java.util.Date

@Composable
internal fun PlayerCaptionDialog(model: CaptionViewModel, embedded: EmbeddedCaptions?, onDismiss: () -> Unit) {
    val state by model.uiState.collectAsStateWithLifecycle()
    val generated by model.generated.collectAsStateWithLifecycle()
    val tracks by embedded?.tracks?.collectAsStateWithLifecycle() ?: remember { mutableStateOf(emptyList()) }
    val loading by embedded?.loading?.collectAsStateWithLifecycle() ?: remember { mutableStateOf(true) }
    val settings = state.settings
    var newCloudKey by remember { mutableStateOf("") }
    var selectedRegion by remember(state.cloudRegion) {
        mutableStateOf(state.cloudRegion.ifBlank { "germanywestcentral" })
    }
    val device by produceState<CaptionDeviceStats?>(null, model) {
        while (true) { value = withContext(Dispatchers.IO) { model.deviceStats() }; delay(2000) }
    }
    val focus = remember { FocusRequester() }
    LaunchedEffect(Unit) { withFrameNanos { }; runCatching { focus.requestFocus() } }
    Dialog(onDismissRequest = onDismiss, properties = DialogProperties(usePlatformDefaultWidth = false)) {
        Surface(Modifier.fillMaxWidth(0.78f).heightIn(max = 490.dp), color = MaterialTheme.colorScheme.surface,
            contentColor = MaterialTheme.colorScheme.onSurface, shape = MaterialTheme.shapes.large) {
            Column(Modifier.padding(18.dp), verticalArrangement = Arrangement.spacedBy(10.dp)) {
                Text(stringResource(R.string.caption_title), style = MaterialTheme.typography.titleLarge,
                    color = MaterialTheme.colorScheme.primary)
                LazyColumn(Modifier.weight(1f, fill = false), verticalArrangement = Arrangement.spacedBy(10.dp),
                    contentPadding = PaddingValues(3.dp)) {
                    item { Text(stringResource(R.string.caption_local_description), style = MaterialTheme.typography.bodySmall) }
                    device?.let { snapshot ->
                        item { Text(stringResource(R.string.caption_device, snapshot.abi, snapshot.cores, snapshot.totalMemoryMb,
                            snapshot.availableMemoryMb), style = MaterialTheme.typography.bodySmall) }
                        snapshot.availableStorageMb?.let { free ->
                            item { Text(stringResource(R.string.caption_storage_available, free), style = MaterialTheme.typography.bodySmall) }
                        }
                        snapshot.lastExit?.let { report ->
                            item {
                                val reason = stringResource(when (report.kind) {
                                    CaptionExitKind.LOW_MEMORY -> R.string.caption_exit_memory
                                    CaptionExitKind.NATIVE_CRASH -> R.string.caption_exit_native
                                    CaptionExitKind.JAVA_CRASH -> R.string.caption_exit_java
                                    CaptionExitKind.ANR -> R.string.caption_exit_anr
                                    CaptionExitKind.SIGNAL -> R.string.caption_exit_signal
                                    CaptionExitKind.RESOURCE_LIMIT -> R.string.caption_exit_resource
                                    CaptionExitKind.OTHER -> R.string.caption_exit_other
                                })
                                val time = remember(report.timestampMillis) {
                                    DateFormat.getDateTimeInstance(DateFormat.SHORT, DateFormat.MEDIUM)
                                        .format(Date(report.timestampMillis))
                                }
                                Text(stringResource(R.string.caption_last_exit, reason, time, report.statusCode,
                                    report.rssMb.takeIf { it > 0 }?.toString() ?: "—"),
                                    style = MaterialTheme.typography.bodySmall)
                            }
                        }
                    }
                    if (settings.translationBackend == TranslationBackend.OFFLINE) item {
                        val mb = CaptionModelCatalog.totalBytes(settings.target.tag, settings.source) / (1024 * 1024)
                        Text(stringResource(R.string.caption_download_size, mb), style = MaterialTheme.typography.bodySmall)
                    }
                    item {
                        AppButton((if (settings.mode == CaptionMode.OFF) "✓ " else "") + stringResource(R.string.caption_off), { model.save(settings.copy(mode = CaptionMode.OFF)) },
                            Modifier.fillMaxWidth().focusRequester(focus), enabled = state.loaded && !state.saving)
                    }
                    item { AppButton((if (settings.mode == CaptionMode.EMBEDDED) "✓ " else "") + stringResource(R.string.caption_embedded), { model.save(settings.copy(mode = CaptionMode.EMBEDDED)) },
                        Modifier.fillMaxWidth(), enabled = state.loaded && !state.saving) }
                    item { AppButton((if (settings.mode == CaptionMode.GENERATED) "✓ " else "") + stringResource(R.string.caption_generate), { model.save(settings.copy(mode = CaptionMode.GENERATED)) },
                        Modifier.fillMaxWidth(), enabled = state.loaded && !state.saving) }
                    item { Text(stringResource(R.string.cloud_engine_title), style = MaterialTheme.typography.titleMedium) }
                    item {
                        AppButton((if (settings.translationBackend == TranslationBackend.OFFLINE) "✓ " else "") +
                            stringResource(R.string.cloud_engine_offline), {
                                model.save(settings.copy(translationBackend = TranslationBackend.OFFLINE))
                            }, Modifier.fillMaxWidth(), enabled = state.loaded && !state.saving)
                    }
                    item {
                        AppButton((if (settings.translationBackend == TranslationBackend.CLOUD) "✓ " else "") +
                            stringResource(R.string.cloud_engine_online), {
                                model.save(settings.copy(translationBackend = TranslationBackend.CLOUD))
                            }, Modifier.fillMaxWidth(), enabled = state.loaded && !state.saving)
                    }
                    item { Text(stringResource(R.string.cloud_audio_notice), style = MaterialTheme.typography.bodySmall) }
                    item { Text(stringResource(if (state.cloudConfigured) R.string.cloud_key_saved else
                        R.string.cloud_key_missing), style = MaterialTheme.typography.bodySmall) }
                    item {
                        OutlinedTextField(value = newCloudKey, onValueChange = { newCloudKey = it.take(300) },
                            modifier = Modifier.fillMaxWidth(), label = { Text(stringResource(R.string.cloud_key_label)) },
                            singleLine = true, visualTransformation = PasswordVisualTransformation(),
                            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password))
                    }
                    item {
                        OutlinedTextField(value = selectedRegion, onValueChange = { selectedRegion = it.take(40) },
                            modifier = Modifier.fillMaxWidth(), label = { Text(stringResource(R.string.cloud_region_label)) },
                            singleLine = true)
                    }
                    item {
                        AppButton(stringResource(R.string.cloud_key_save), {
                            model.saveCloudCredentials(newCloudKey, selectedRegion)
                            newCloudKey = ""
                        }, Modifier.fillMaxWidth(), enabled = !state.cloudSaving && newCloudKey.length >= 10)
                    }
                    if (state.cloudConfigured) item {
                        AppButton(stringResource(R.string.cloud_key_remove), model::deleteCloudCredentials,
                            Modifier.fillMaxWidth(), enabled = !state.cloudSaving)
                    }
                    if (state.cloudSaveFailed) item {
                        Text(stringResource(R.string.cloud_key_error), color = MaterialTheme.colorScheme.error)
                    }
                    item { Text(stringResource(R.string.caption_target), style = MaterialTheme.typography.titleMedium) }
                    item {
                        Row(horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                            CaptionLanguage.entries.forEach { language ->
                                AppButton((if (settings.target == language) "✓ " else "") + language.nativeName,
                                    { model.save(settings.copy(target = language)) }, Modifier.weight(1f),
                                    enabled = state.loaded && !state.saving)
                            }
                        }
                    }
                    item {
                        val names = listOf("auto") + CaptionLanguage.entries.map { it.tag }
                        val label = if (settings.source == "auto") stringResource(R.string.caption_auto) else
                            CaptionLanguage.fromTag(settings.source)?.nativeName.orEmpty()
                        AppButton(stringResource(R.string.caption_source, label), {
                            model.save(settings.copy(source = names[(names.indexOf(settings.source) + 1) % names.size]))
                        }, Modifier.fillMaxWidth(), enabled = state.loaded && !state.saving)
                    }
                    item {
                        val size = stringResource(when (settings.textSize) {
                            CaptionTextSize.SMALL -> R.string.caption_small
                            CaptionTextSize.MEDIUM -> R.string.caption_medium
                            CaptionTextSize.LARGE -> R.string.caption_large
                        })
                        AppButton(stringResource(R.string.caption_size, size), {
                            model.save(settings.copy(textSize = CaptionTextSize.entries[(settings.textSize.ordinal + 1) % CaptionTextSize.entries.size]))
                        }, Modifier.fillMaxWidth(), enabled = state.loaded && !state.saving)
                    }
                    item { AppButton(stringResource(if (settings.shaded) R.string.caption_background_on else R.string.caption_background_off),
                        { model.save(settings.copy(shaded = !settings.shaded)) }, Modifier.fillMaxWidth(), enabled = state.loaded && !state.saving) }
                    item { Text(stringResource(R.string.caption_tracks), style = MaterialTheme.typography.titleMedium) }
                    if (tracks.isEmpty()) item { Text(stringResource(if (loading) R.string.caption_tracks_loading else R.string.caption_no_tracks)) }
                    items(tracks.size) { index ->
                        val track = tracks[index]
                        AppButton((if (track.selected) "✓ " else "") + track.label, {
                            embedded?.select(track)?.let(model::save)
                        }, Modifier.fillMaxWidth(), enabled = state.loaded && !state.saving)
                    }
                    if (settings.mode == CaptionMode.GENERATED) {
                        item { Text(captionStatusText(generated.progress), style = MaterialTheme.typography.bodyMedium) }
                        generated.timing?.let { timing ->
                            item { Text(stringResource(R.string.caption_timing, timing.audioMillis, timing.speechMillis,
                                timing.translationMillis, timing.memoryMillis), style = MaterialTheme.typography.bodySmall) }
                        }
                        if (settings.source == settings.target.tag) {
                            item { Text(stringResource(R.string.caption_direct), style = MaterialTheme.typography.bodySmall) }
                        }
                        item { AppButton(stringResource(R.string.caption_retry), model::retry) }
                    }
                    if (state.readFailed) item { Text(stringResource(R.string.caption_read_error)); AppButton(stringResource(R.string.caption_retry), model::reload) }
                    if (state.saveFailed) item { Text(stringResource(R.string.caption_save_error), color = MaterialTheme.colorScheme.error) }
                }
                AppButton(stringResource(R.string.ui_back), onDismiss, Modifier.fillMaxWidth())
            }
        }
    }
}